const { test, expect } = require('@playwright/test');
const AxeBuilder = require('@axe-core/playwright').default;

test('indexed discovery, private matching, filters, pagination, errors and export', async ({page, request}) => {
  const errors=[]; page.on('pageerror', error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('button',{name:/Search everything/})).toHaveAttribute('aria-pressed','true');
  await page.getByRole('button',{name:'Refresh sources',exact:true}).click();
  await expect(page.locator('#discoveryCount')).toHaveText('135',{timeout:15000});
  await expect(page.locator('#resultsSummary')).toContainText('Showing 60 of 135');
  await expect(page.locator('#coverageHealth')).toContainText('Unavailable Example');
  await expect(page.locator('#coverageHealth')).toContainText('error');
  await page.getByRole('button',{name:/Load more jobs/}).click();
  await expect(page.locator('#jobList article')).toHaveCount(120);
  await page.getByRole('button',{name:/Search for me/}).click();
  await expect(page.locator('#resultsSummary')).toContainText('of 85 matching');
  await page.getByRole('button',{name:/Search everything/}).click();
  await expect(page.locator('#resultsSummary')).toContainText('of 135 matching');
  await page.locator('[data-industry="healthcare"]').click();
  await expect(page.locator('#resultsSummary')).toContainText('of 50 matching');
  await page.locator('[data-industry="all"]').click();
  await page.locator('#occupationFilter').fill('research');
  await expect(page.locator('#resultsSummary')).toContainText('of 50 matching');
  await page.locator('#occupationFilter').fill('');
  await page.locator('#salaryFilter').fill('70000');
  await expect(page.locator('#resultsSummary')).toContainText('of 68 matching');
  await page.locator('#workplaceFilter').selectOption('hybrid');
  await expect(page.locator('#resultsSummary')).toContainText('of 0 matching');
  await page.locator('#salaryFilter').fill('');
  await page.locator('#workplaceFilter').selectOption('');
  await page.locator('#locationFilter').fill('Edinburgh');
  await expect(page.locator('#resultsSummary')).toContainText('of 0 matching');
  await page.locator('#locationFilter').fill('');
  await page.locator('#searchInput').fill('Risk Manager 000');
  await expect(page.locator('#jobList article')).toHaveCount(1);
  await expect(page.locator('#jobList img')).toHaveCount(0);
  await page.getByRole('button',{name:'Save job',exact:true}).click();
  await page.getByRole('button',{name:/My applications/}).click();
  await expect(page.locator('#trackerList article')).toHaveCount(1);
  const exported=await request.get('/api/export');
  expect((await exported.json()).tracker['lever:bank:0'].title).toBe('Risk Manager 000');
  const crossOrigin=await request.post('/api/refresh',{data:{},headers:{Origin:'https://evil.example'}});
  expect(crossOrigin.status()).toBe(403);
  await page.getByRole('button',{name:/Discover jobs/}).first().click();
  await page.getByRole('button',{name:'Preview example jobs'}).click();
  await expect(page.locator('#sourceStatus')).toContainText('DEMONSTRATION');
  expect(errors).toEqual([]);
});

test('keyboard labels, accessible results and mobile layout', async ({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'Preview example jobs'}).click();
  await expect(page.locator('#discoveryCount')).toHaveText('10');
  const scan=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  expect(scan.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))}))).toEqual([]);
  if (process.env.UK_HUNTER_SCREENSHOTS) await page.screenshot({path:process.env.UK_HUNTER_SCREENSHOTS+'/desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  if (process.env.UK_HUNTER_SCREENSHOTS) await page.screenshot({path:process.env.UK_HUNTER_SCREENSHOTS+'/mobile.png',fullPage:true});
});
